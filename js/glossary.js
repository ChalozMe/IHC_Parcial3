    const IRR = { led: 'lead', met: 'meet', left: 'leave', broke: 'break', broken: 'break', rose: 'rise', risen: 'rise', breaks: 'break', overcame: 'overcome', dealt: 'deal', companies: 'company' };
    /* Posibles formas base de una palabra */
    function lemmas(word) {
        const w = word.toLowerCase().replace(/['’]s$/, '');
        const c = [w];
        if (IRR[w]) c.push(IRR[w]);
        if (/ies$/.test(w)) c.push(`${w.slice(0, -3)}y`);
        if (/ied$/.test(w)) c.push(`${w.slice(0, -3)}y`);
        if (/es$/.test(w)) c.push(w.slice(0, -2));
        if (/s$/.test(w)) c.push(w.slice(0, -1));
        if (/ed$/.test(w)) c.push(w.slice(0, -2), w.slice(0, -1));
        if (/ing$/.test(w)) c.push(w.slice(0, -3), `${w.slice(0, -3)}e`);
        if (/(.)\1(?:ed|ing)$/.test(w)) c.push(w.replace(/(.)\1(?:ed|ing)$/, '$1'));
        return c;
    }
    function lookup(word) {
        const l = lemmas(word).find((x) => DICT[x]);
        return l ? { lemma: l, senses: DICT[l] } : null;
    }
    /* ¿La oración usa la palabra en alguna forma? */
    function uses(sentence, word) {
        const target = new Set(lemmas(word));
        return (sentence.toLowerCase().match(/[a-z]+(?:['’][a-z]+)?/g) || []).some((t) => lemmas(t).some((x) => target.has(x)));
    }

    window.Glossary = { DICT, lookup, uses, size: Object.keys(DICT).length };
